import { Modal, Pressable, StyleSheet, Switch, Text, View } from 'react-native';
import { CloseMark, LogoutMark } from './NexusMark';
import { BrandLogo } from './BrandLogo';
import { BRAND_NAME } from '../theme/brand';
import { fruitRing, fruitWash, jungle } from '../theme/jungle';
import { JungleBackdrop } from './JungleBackdrop';
import { drawerMarks, profileModules, socialTokens } from '../theme/social';

/**
 * The drawer of the bar. It is small and has no words: one tile per module of Nexus and one tile that
 * ends the session. Markup and geometry come from apps/nexus-web/public/feed-surface.js
 * (`feedQuickDrawerMarkup`, `feedQuickTilesMarkup`) and feed-surface.css:127-141.
 * The tiles are built every time the drawer opens, so the module being read is marked from the state
 * at that moment and a drawer that moved never answers from a stale list.
 */
export type FeedDrawerProps = {
  open: boolean;
  activeModule: string;
  onClose: () => void;
  onModule: (id: string) => void;
  onLogout: () => void;
  onNewPost: () => void;
  /**
   * The door to the account's activity: the inbox's own activity box, which is the only surface this
   * app has for notifications (`ActivityCenter`, `GET /api/notifications`). The drawer is the index of
   * doors the account screen opens with its three bars, so the bell belongs here rather than on a
   * header that has no room for it (`MIGRATION.md` §22).
   */
  onNotifications: () => void;
  /**
   * `Banda derulantă`: the reader's own switch for the profile band's motion (`MIGRATION.md` §20.2). The
   * band no longer asks the system for reduced motion; this switch — on by default — is the only way to
   * stop it, and the drawer is the one index an account can open from every screen.
   */
  bandScrolling: boolean;
  onBandScrolling: (on: boolean) => void;
  /**
   * The build line printed at the foot of the drawer: the app version and which backend it talks to
   * (`Android 0.1.0 · API: Railway`). The login screen prints the same pair, and the drawer is the one
   * surface an already-signed-in reader can always open, so the origin is never a guess.
   */
  version: string;
  /**
   * The JavaScript this screen is running (`lib/buildStamp.ts`): short commit and the moment the stamp was
   * taken, with a `+` when the tree was dirty. Regenerated by `node scripts/stamp-build.mjs`; a stale value
   * here is exactly the "Metro is serving old code" signal the owner asked for.
   */
  build: string;
};

export function FeedDrawer({ open, activeModule, onClose, onModule, onLogout, onNewPost, onNotifications, bandScrolling, onBandScrolling, version, build }: FeedDrawerProps) {
  return (
    <Modal visible={open} transparent animationType="fade" onRequestClose={onClose} statusBarTranslucent>
      <Pressable accessibilityRole="button" accessibilityLabel="Închide meniul" onPress={onClose} style={styles.backdrop} />
      <View accessibilityRole="menu" accessibilityLabel="Schimbă profilul" style={styles.drawer}>
        <JungleBackdrop opacity={0.07} />
        <Pressable accessibilityRole="button" accessibilityLabel="Închide" onPress={onClose} style={styles.close}>
          <CloseMark size={18} />
        </Pressable>
        {/* The drawer names the product: the mark and the name, above the index of doors. */}
        <View style={styles.brandRow}>
          <BrandLogo variant="nav" size={24} />
          <Text style={styles.brandName}>{BRAND_NAME}</Text>
        </View>
        <View style={styles.grid}>
          {profileModules.map((module) => {
            const active = module.id === activeModule;
            return (
              <Pressable
                key={module.id}
                accessibilityRole="button"
                accessibilityLabel={module.title}
                accessibilityState={{ selected: active }}
                onPress={() => onModule(module.id)}
                style={({ pressed }) => [styles.tile, active && styles.tileActive, pressed && { transform: [{ scale: 0.94 }] }]}
              >
                <Text style={[styles.tileGlyph, active && styles.tileGlyphActive]}>{drawerMarks[module.id] ?? module.glyph}</Text>
              </Pressable>
            );
          })}
          {/* A new post is the one action the drawer needs beyond the five profiles. */}
          <Pressable
            accessibilityRole="button"
            accessibilityLabel="Postare nouă"
            onPress={() => { onClose(); onNewPost(); }}
            style={({ pressed }) => [styles.tile, pressed && { transform: [{ scale: 0.94 }] }]}
          >
            <Text style={styles.tileGlyph}>＋</Text>
          </Pressable>
          {/* And the bell: the account's activity, in the inbox box that already reads it. */}
          <Pressable
            accessibilityRole="button"
            accessibilityLabel="Notificări"
            onPress={() => { onClose(); onNotifications(); }}
            style={({ pressed }) => [styles.tile, styles.tileBell, pressed && { transform: [{ scale: 0.94 }] }]}
          >
            <Text style={styles.tileGlyph}>🔔</Text>
          </Pressable>
        </View>
        {/* The reader's own switch for the band's motion: the product's rule, not the system's. */}
        <Pressable
          accessibilityRole="switch"
          accessibilityLabel="Banda derulantă"
          accessibilityState={{ checked: bandScrolling }}
          onPress={() => onBandScrolling(!bandScrolling)}
          style={styles.pref}
        >
          <Text style={styles.prefLabel}>Banda derulantă</Text>
          <Switch
            value={bandScrolling}
            pointerEvents="none"
            trackColor={{ false: 'rgba(255,255,255,0.2)', true: '#2fbdb3' }}
            thumbColor="#eef8fb"
          />
        </Pressable>
        <Pressable
          accessibilityRole="button"
          accessibilityLabel="Ieși din cont"
          onPress={onLogout}
          style={({ pressed }) => [styles.logout, pressed && { transform: [{ scale: 0.94 }] }]}
        >
          <LogoutMark size={19} />
        </Pressable>
        <Text accessibilityRole="text" style={styles.version}>{`${BRAND_NAME} · ${version}`}</Text>
        {/** The JS build the phone is really running: commit and the moment the stamp was taken. */}
        <Text accessibilityRole="text" accessibilityLabel={`Build ${build}`} style={styles.build}>{`build ${build}`}</Text>
      </View>
    </Modal>
  );
}

