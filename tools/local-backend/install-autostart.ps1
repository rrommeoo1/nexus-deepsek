# Installs the backend so it starts with Windows, hidden, and stays up.
#
# Three pieces:
#   1. a tiny VBS launcher in C:\Nexus\bin, which starts the supervisor with a hidden window ??? a console
#      window that flashes every time the service starts is exactly what this avoids;
#   2. a Scheduled Task ("Jungle Book Backend") that runs that launcher at logon and again daily, hidden,
#      with MultipleInstances=IgnoreNew so a second copy can never fight for the port;
#   3. the supervisor itself (jungle-backend-service.mjs), which owns restart-on-crash and health probes,
#      because a scheduled task cannot tell a hung server from a healthy one.
#
# The older task ("Nexus Social 5000") started `server.js` directly on the same port. It is stopped and
# disabled rather than deleted, so a rollback is one command away.
#
#   powershell -ExecutionPolicy Bypass -File tools\local-backend\install-autostart.ps1
param(
  [string]$NexusHome = 'C:\Nexus',
  [string]$TaskName = 'Jungle Book Backend',
  [string]$LegacyTaskName = 'Nexus Social 5000',
  [switch]$KeepLegacyRunning
)

$ErrorActionPreference = 'Stop'
$repo = (Resolve-Path (Join-Path $PSScriptRoot '..\..')).Path
$node = (Get-Command node).Source
$supervisor = Join-Path $repo 'tools\local-backend\jungle-backend-service.mjs'
$binDir = Join-Path $NexusHome 'bin'
$launcher = Join-Path $binDir 'jungle-backend.vbs'

New-Item -ItemType Directory -Force -Path $binDir | Out-Null

$vbs = @"
' Jungle Book backend launcher ??? generated by install-autostart.ps1.
' Runs the supervisor with no window at all, then exits immediately: the scheduled task's job is to make
' sure something started, and the supervisor's job is to keep it running.
Set shell = CreateObject("WScript.Shell")
shell.CurrentDirectory = "$repo"
shell.Run """" & "$node" & """ ""$supervisor""", 0, False
"@
Set-Content -Path $launcher -Value $vbs -Encoding ASCII
Write-Output "launcher written: $launcher"

# 1. Register the task.
$action = New-ScheduledTaskAction -Execute 'wscript.exe' -Argument "`"$launcher`"" -WorkingDirectory $repo
$atLogon = New-ScheduledTaskTrigger -AtLogOn -User "$env:USERDOMAIN\$env:USERNAME"
$daily = New-ScheduledTaskTrigger -Daily -At 00:05
$settings = New-ScheduledTaskSettingsSet -MultipleInstances IgnoreNew -RestartCount 999 -RestartInterval (New-TimeSpan -Minutes 1) -AllowStartIfOnBatteries -DontStopIfGoingOnBatteries -StartWhenAvailable -ExecutionTimeLimit (New-TimeSpan -Days 0)
$settings.Hidden = $true
$principal = New-ScheduledTaskPrincipal -UserId "$env:USERDOMAIN\$env:USERNAME" -LogonType Interactive -RunLevel Limited

if (Get-ScheduledTask -TaskName $TaskName -ErrorAction SilentlyContinue) {
  Unregister-ScheduledTask -TaskName $TaskName -Confirm:$false
}
Register-ScheduledTask -TaskName $TaskName -Action $action -Trigger @($atLogon, $daily) -Settings $settings -Principal $principal | Out-Null
Write-Output "task registered: $TaskName (logon + daily 00:05, hidden, restart 999x/1min, ignore new instances)"

# 2. The old task on the same port must not race the new one.
$legacy = Get-ScheduledTask -TaskName $LegacyTaskName -ErrorAction SilentlyContinue
if ($legacy) {
  if ($legacy.State -eq 'Running') { Stop-ScheduledTask -TaskName $LegacyTaskName }
  Disable-ScheduledTask -TaskName $LegacyTaskName | Out-Null
  Write-Output "legacy task disabled (kept for rollback): $LegacyTaskName"
  if ($KeepLegacyRunning) { Write-Output 'note: -KeepLegacyRunning was given, but the legacy task shares the port and stays disabled' }
}

# 3. Any plain `node server.js` left over from a manual start would hold the port too.
$port = 5000
$envFile = Join-Path $NexusHome 'env\jungle.env'
if (Test-Path $envFile) {
  $line = (Get-Content $envFile | Where-Object { $_ -match '^\s*PORT\s*=' } | Select-Object -First 1)
  if ($line) { $port = [int](($line -split '=', 2)[1].Trim()) }
}
$holders = Get-NetTCPConnection -State Listen -LocalPort $port -ErrorAction SilentlyContinue
foreach ($holder in $holders) {
  $process = Get-CimInstance Win32_Process -Filter "ProcessId=$($holder.OwningProcess)" -ErrorAction SilentlyContinue
  if ($process -and $process.CommandLine -match 'server\.js') {
    Write-Output "port $port held by pid $($holder.OwningProcess) ($($process.CommandLine)); stopping it"
    Stop-Process -Id $holder.OwningProcess -Force
    Start-Sleep -Seconds 1
  }
}

Start-ScheduledTask -TaskName $TaskName
Write-Output "task started: $TaskName"
Write-Output 'check with: powershell -ExecutionPolicy Bypass -File tools\local-backend\status-backend.ps1'


